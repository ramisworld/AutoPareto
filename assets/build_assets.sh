#!/usr/bin/env bash
# build_assets.sh -- rebuild the AutoPareto asset folder from public sources.
#
#   bash assets/build_assets.sh /workspace/assets
#
# Downloads, from pinned Hugging Face revisions, the 10 training shards, the validation shard and the held-out
# shard of karpathy/climbmix-400b-shuffle (revision 915333b4...) and the two cu128 builds of
# kernels-community/flash-attn3 (revision e29f138f...). It lays them out exactly as assets/install_assets.sh
# expects, regenerates the tokenizer with prepare.py, checks every file against the SHA-256 values embedded in
# install_assets.sh, and writes SHA256SUMS. The result is what scripts/pod/fresh_a40_bootstrap.sh calls
# /workspace/assets. About 2.6 GB. Nothing is overwritten: the output folder must not exist.
#
# Environment:
#   AP_PYTHON      Python used to regenerate the tokenizer (needs rustbpe, tiktoken, pyarrow, numpy, torch);
#                  on the pod use the Env B runtime, /opt/autopareto_runtime/bin/python. Default: python3.
#   AP_HF_BASE     Base URL of the Hub. Default: https://huggingface.co (tests point it at a local mirror).
#   AP_SKIP_TOKENIZER=1  stop before the tokenizer (for testing the download and layout only).
#
# The tokenizer's token_bytes.pt matches the recorded hash only on Linux: a macOS torch.save writes a different
# 40-byte serialization_id record. Run this script on the Linux GPU machine.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
ROOT="$(cd "$HERE/.." && pwd -P)"
OUT="${1:?usage: bash assets/build_assets.sh <new output folder>}"
PY="${AP_PYTHON:-python3}"
HF="${AP_HF_BASE:-https://huggingface.co}"
DREV=915333b4f8b8684f39aeaafea600fea6f43fb703
KREV=e29f138fc363b396e5d2706c8a5f6fa7d36f41e0
KDIR=huggingface/hub/models--kernels-community--flash-attn3

die() { echo "build_assets.sh: ERROR: $*" >&2; exit 1; }
say() { echo "build_assets.sh: $*"; }
sha() { sha256sum "$1" | cut -d' ' -f1; }
fetch() {  # fetch <url> <dest>: download once, atomically
  [ -f "$2" ] && return 0
  mkdir -p "$(dirname "$2")"
  curl -fsSL --retry 5 --retry-delay 3 --connect-timeout 30 -o "$2.part" "$1" || die "download failed: $1"
  mv "$2.part" "$2"
}
check() {  # check <file> <expected sha256>
  local got
  got="$(sha "$1")"
  [ "$got" = "$2" ] || die "sha256 mismatch for $1: got $got, expected $2"
}

for tool in curl sha256sum ln sed; do command -v "$tool" >/dev/null || die "required tool not found: $tool"; done
[ ! -e "$OUT" ] || die "$OUT already exists; refusing to overwrite"
MANIFEST="$(sed -n "/^MANIFEST='/,/'\$/p" "$HERE/install_assets.sh" | sed -e "s/^MANIFEST='//" -e "s/'\$//")"
[ "$(printf '%s\n' "$MANIFEST" | grep -c '|')" = 46 ] || die "could not read the 46-entry manifest from install_assets.sh"
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd -P)"

say "1/3 data shards and flash-attn3 files from pinned revisions"
while IFS='|' read -r kind rel want target; do
  [ -n "$kind" ] || continue
  case "$rel" in
    autoresearch_cache/tokenizer/*) ;;  # regenerated in step 2
    autoresearch_cache/data/*)
      fetch "$HF/datasets/karpathy/climbmix-400b-shuffle/resolve/$DREV/${rel##*/}" "$OUT/$rel"
      check "$OUT/$rel" "$want" ;;
    autopareto_downstream/*)
      name="${rel##*/}"
      fetch "$HF/datasets/karpathy/climbmix-400b-shuffle/resolve/$DREV/${name#"$DREV"-}" "$OUT/$rel"
      check "$OUT/$rel" "$want" ;;
    "$KDIR/refs/main")
      mkdir -p "$(dirname "$OUT/$rel")"
      printf '%s' "$KREV" > "$OUT/$rel"   # huggingface_hub writes the bare commit hash, no newline
      check "$OUT/$rel" "$want" ;;
    "$KDIR/blobs/"*) ;;  # filled through the snapshot links below, then checked in the pass after this loop
    "$KDIR/snapshots/$KREV/"*)
      [ "$kind" = link ] || die "unexpected manifest entry: $kind|$rel"
      link="$OUT/$rel"
      mkdir -p "$(dirname "$link")"
      blob="$(dirname "$link")/$target"
      fetch "$HF/kernels-community/flash-attn3/resolve/$KREV/${rel#"$KDIR/snapshots/$KREV/"}" "$blob"
      ln -s "$target" "$link"
      check "$link" "$want" ;;
    *) die "unexpected manifest entry: $rel" ;;
  esac
done <<EOF
$MANIFEST
EOF
while IFS='|' read -r kind rel want target; do  # every blob is present and has its recorded hash
  case "$rel" in "$KDIR/blobs/"*) check "$OUT/$rel" "$want" ;; esac
done <<EOF
$MANIFEST
EOF

if [ "${AP_SKIP_TOKENIZER:-0}" = 1 ]; then
  say "AP_SKIP_TOKENIZER=1: stopping before the tokenizer; $OUT is incomplete"
  exit 0
fi

say "2/3 tokenizer, regenerated by prepare.py from the shards above"
TMP_HOME="$(mktemp -d)"
trap 'rm -rf "$TMP_HOME"' EXIT
mkdir -p "$TMP_HOME/.cache"
ln -s "$OUT/autoresearch_cache" "$TMP_HOME/.cache/autoresearch"
# prepare.py reads and writes ~/.cache/autoresearch; all 11 shards already exist there, so it downloads nothing.
(cd "$ROOT" && HOME="$TMP_HOME" "$PY" prepare.py --num-shards 10 --download-workers 1)
while IFS='|' read -r kind rel want target; do
  case "$rel" in
    autoresearch_cache/tokenizer/*)
      [ -f "$OUT/$rel" ] || die "prepare.py did not write $rel"
      check "$OUT/$rel" "$want" ;;
  esac
done <<EOF
$MANIFEST
EOF

say "3/3 installer and SHA256SUMS"
cp "$HERE/install_assets.sh" "$OUT/install_assets.sh"
(cd "$OUT" && find . -type f ! -name SHA256SUMS ! -name '*.part' | LC_ALL=C sort | while read -r f; do sha256sum "$f"; done > SHA256SUMS)
say "done: $OUT ($(wc -l < "$OUT/SHA256SUMS" | tr -d ' ') files). Next: bash scripts/pod/fresh_a40_bootstrap.sh assets"
